/// An icon's SVG by its Lucide name (`rocket`, `chart-line`).
pub fn svg(name: &str) -> Option<Cow<'static, [u8]>> {
    SlideIcons
        .load(&format!("icons/{}.svg", name.trim().to_lowercase()))
        .ok()
        .flatten()
}

/// Every icon's name.
pub fn names() -> Vec<String> {
    SlideIcons
        .list("icons/")
        .unwrap_or_default()
        .iter()
        .map(|path| {
            path.trim_start_matches("icons/")
                .trim_end_matches(".svg")
                .to_string()
        })
        .collect()
}

#[cfg(test)]
mod tests {
    #[test]
    fn icons_load_by_name() {
        assert!(super::svg("rocket").is_some());
        assert!(super::svg("Chart-Line").is_some());
        assert!(super::svg("no-such-icon").is_none());
        assert!(super::names().len() > 200);
    }
}
